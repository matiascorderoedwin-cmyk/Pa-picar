-- Rellenos opcionales para tarticos, y endpoints de avisos voluntarios.
ALTER TABLE public.pedido_detalles ADD COLUMN IF NOT EXISTS relleno VARCHAR(12);
CREATE TABLE IF NOT EXISTS public.suscripciones_push (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 endpoint TEXT NOT NULL UNIQUE, p256dh TEXT NOT NULL, auth TEXT NOT NULL,
 origen TEXT NOT NULL, creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS suscripciones_push_usuario_idx ON public.suscripciones_push(usuario_id);
ALTER TABLE public.suscripciones_push ENABLE ROW LEVEL SECURITY;

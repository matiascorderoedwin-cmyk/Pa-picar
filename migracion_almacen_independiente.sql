-- Almacén separado de productos de venta. Migración aditiva sin alterar pedidos, ventas ni productos.
CREATE TABLE IF NOT EXISTS public.almacen_articulos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    cantidad INTEGER NOT NULL DEFAULT 0 CHECK (cantidad BETWEEN 0 AND 100000000),
    unidad VARCHAR(30) NOT NULL DEFAULT 'unidades',
    ubicacion VARCHAR(100) NOT NULL DEFAULT '',
    nota VARCHAR(300) NOT NULL DEFAULT '',
    archivado BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT almacen_articulos_nombre_no_vacio CHECK (length(btrim(nombre)) >= 2),
    CONSTRAINT almacen_articulos_unidad_no_vacia CHECK (length(btrim(unidad)) >= 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS almacen_articulos_nombre_ci_uidx
    ON public.almacen_articulos ((lower(btrim(nombre))));
CREATE TABLE IF NOT EXISTS public.almacen_movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    articulo_id BIGINT NOT NULL REFERENCES public.almacen_articulos(id) ON DELETE RESTRICT,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('Alta', 'Ajuste')),
    cambio INTEGER NOT NULL CHECK (cambio <> 0),
    detalle VARCHAR(260) NOT NULL DEFAULT '',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS almacen_movimientos_articulo_fecha_idx
    ON public.almacen_movimientos (articulo_id, id DESC);
ALTER TABLE public.almacen_articulos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.almacen_movimientos ENABLE ROW LEVEL SECURITY;
